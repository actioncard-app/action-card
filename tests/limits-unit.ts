// Unit tests: free Core limits (4 scans per 30-day period that starts at the first scan, sample not counted, 1 saved
// letter, Pro unlocks all, Pro switched off in the build = no limits).
import { canSaveAnother, canScan, coreLimited, countScan, FREE_PERIOD_DAYS, FREE_SAVED_LETTERS, FREE_SCANS, resetDate, scansLeft, scansUsed } from '../src/lib/limits';
import { offersFreeTrial } from '../src/lib/pro';
import { S2 } from '../src/lib/i18n-v2';
let n = 0, fail = 0;
const ok = (name: string, c: boolean) => { n++; if (!c) { fail++; console.log('FAIL  ' + name); } else console.log('PASS  ' + name); };
const mem = () => { const m = new Map<string, string>(); return { getItem: (k: string) => m.get(k) ?? null, setItem: (k: string, v: string) => { m.set(k, v); } }; };
const D = 86_400_000;
const t0 = new Date(2026, 10, 3, 12, 0), at = (days: number) => new Date(t0.getTime() + days * D);
ok('free scans = 4 per 30 days, saved letters = 1', FREE_SCANS === 4 && FREE_PERIOD_DAYS === 30 && FREE_SAVED_LETTERS === 1);
const s = mem();
ok('new device: 4 left, no reset date yet', scansLeft(t0, s) === 4 && canScan(false, t0, s, true) && resetDate(t0, s) === null);
countScan(t0, s);
ok('after 1 scan: 3 left', scansLeft(t0, s) === 3 && canScan(false, t0, s, true));
ok('reset date = first scan + 30 days', resetDate(t0, s)?.getTime() === at(30).getTime());
countScan(at(5), s);
ok('after 2 scans: 2 left; a later scan does not move the reset date', scansLeft(at(5), s) === 2 && resetDate(at(5), s)?.getTime() === at(30).getTime());
countScan(at(10), s);
ok('after 3 scans: 1 left', scansLeft(at(10), s) === 1 && canScan(false, at(10), s, true));
countScan(at(20), s);
ok('after 4 scans: 0 left, 5th scan blocked', scansLeft(at(20), s) === 0 && !canScan(false, at(20), s, true));
ok('still blocked one minute before the reset', !canScan(false, new Date(at(30).getTime() - 60000), s, true));
ok('Pro owned: never blocked', canScan(true, at(20), s, true));
ok('Pro off in this build: never blocked (no way to buy)', canScan(false, at(20), s, false) && !coreLimited(false, false));
ok('30 days after the first scan: 4 left again, no reset date', scansUsed(at(30), s) === 0 && scansLeft(at(30), s) === 4 && resetDate(at(30), s) === null);
countScan(at(31), s);
ok('next period starts at the next scan (day 31): 3 left, resets day 61', scansLeft(at(31), s) === 3 && resetDate(at(31), s)?.getTime() === at(61).getTime());
ok('calendar month change does not reset (Nov 3 -> Dec 1 inside one period)', scansLeft(new Date(2026, 11, 1), (() => { const m = mem(); countScan(t0, m); countScan(t0, m); return m; })()) === 2);
const bad = mem(); bad.setItem('letterscan.scans.v2', '{oops');
ok('corrupt counter reads as 0 used', scansUsed(t0, bad) === 0);
const old = mem(); old.setItem('letterscan.scans.v1', JSON.stringify({ month: '2026-11', n: 2 }));
ok('old calendar-month counter (v1) is ignored: 4 left', scansLeft(t0, old) === 4);
ok('sample not counted: nothing is counted without countScan', scansUsed(t0, mem()) === 0);
ok('save: 0 saved -> may save 1', canSaveAnother(false, 0, true));
ok('save: 1 saved -> 2nd blocked in Core', !canSaveAnother(false, 1, true));
ok('save: Pro -> unlimited', canSaveAnother(true, 50, true));
ok('save: Pro off in build -> unlimited', canSaveAnother(false, 50, false));
ok('trial: free intro offer + eligible -> trial', offersFreeTrial({ introductoryPrice: { price: 0 }, introEligibility: 2 }));
ok('trial: eligibility unknown -> trial shown', offersFreeTrial({ introductoryPrice: { price: 0 } }));
ok('trial: ineligible (used before) -> no trial', !offersFreeTrial({ introductoryPrice: { price: 0 }, introEligibility: 1 }));
ok('trial: no intro offer -> no trial', !offersFreeTrial({ introductoryPrice: null }) && !offersFreeTrial(null));
ok('trial: paid intro price is not a free trial', !offersFreeTrial({ introductoryPrice: { price: 0.99 } }));
const keys = ['core_scans_left', 'core_resets', 'core_limit_title', 'core_limit_body', 'core_save_title', 'core_save_body', 'core_replace', 'core_pro_only', 'core_steps_teaser', 'core_pdf_first', 'core_free_note', 'pro_lead_core', 'pro_f_unlimited', 'pro_f_plan', 'pro_f_voices', 'pro_f_history', 'pro_f_export', 'pro_f_qr', 'pro_trial_line', 'pro_start_trial', 'pro_trial_terms', 'pro_price_store'] as const;
const ph = (x: string) => (x.match(/\{\w+\}/g) ?? []).sort().join();
for (const k of keys) ok(`${k}: 18 languages, same placeholders`, S2[k].length === 18 && S2[k].every((x) => x.trim().length > 0 && ph(x) === ph(S2[k][0])));
ok('trial terms: 7 days, {price}, 24 hours, Apple ID in every language', S2.pro_trial_terms.every((x) => /7|۷/.test(x) && x.includes('{price}') && /24|۲۴/.test(x) && /Apple[ -]ID|Apple Kimliği/.test(x)));
ok('English trial terms: renews automatically, cancel 24 hours before the trial ends', /renews automatically every month/.test(S2.pro_trial_terms[0]) && /24 hours before the trial ends/.test(S2.pro_trial_terms[0]));
ok('no "month" wording left in English free-tier strings', !/month/i.test(S2.core_scans_left[0] + S2.core_limit_title[0] + S2.core_limit_body[0] + S2.core_free_note[0]));
console.log(`${n - fail} limits checks passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
