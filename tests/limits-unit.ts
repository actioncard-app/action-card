// Unit tests: free Core limits (2 scans per calendar month, sample not counted, 1 saved letter, Pro unlocks all,
// Pro switched off in the build = no limits).
import { canSaveAnother, canScan, coreLimited, countScan, FREE_SAVED_LETTERS, FREE_SCANS_PER_MONTH, monthKey, nextMonthStart, scansLeft, scansUsed } from '../src/lib/limits';
import { offersFreeTrial } from '../src/lib/pro';
import { S2 } from '../src/lib/i18n-v2';
let n = 0, fail = 0;
const ok = (name: string, c: boolean) => { n++; if (!c) { fail++; console.log('FAIL  ' + name); } else console.log('PASS  ' + name); };
const mem = () => { const m = new Map<string, string>(); return { getItem: (k: string) => m.get(k) ?? null, setItem: (k: string, v: string) => { m.set(k, v); } }; };
const oct = new Date(2026, 9, 31, 23, 50), nov = new Date(2026, 10, 1, 0, 5), dec = new Date(2026, 11, 15);
ok('free scans = 2, saved letters = 1', FREE_SCANS_PER_MONTH === 2 && FREE_SAVED_LETTERS === 1);
const s = mem();
ok('new device: 2 left', scansLeft(oct, s) === 2 && canScan(false, oct, s, true));
countScan(oct, s);
ok('after 1 scan: 1 left, may scan', scansLeft(oct, s) === 1 && canScan(false, oct, s, true));
countScan(oct, s);
ok('after 2 scans: 0 left, 3rd scan blocked', scansLeft(oct, s) === 0 && !canScan(false, oct, s, true));
ok('Pro owned: never blocked', canScan(true, oct, s, true));
ok('Pro off in this build: never blocked (no way to buy)', canScan(false, oct, s, false) && !coreLimited(false, false));
ok('month rollover (Oct 31 -> Nov 1): 2 left again', scansUsed(nov, s) === 0 && scansLeft(nov, s) === 2 && canScan(false, nov, s, true));
countScan(nov, s);
ok('counting in Nov starts at 1', scansUsed(nov, s) === 1);
ok('a later month also resets', scansLeft(dec, s) === 2);
ok('month key is the local calendar month', monthKey(oct) === '2026-10' && monthKey(nov) === '2026-11');
ok('free scans come back on the 1st of next month', nextMonthStart(oct).getDate() === 1 && nextMonthStart(oct).getMonth() === 10);
ok('December rolls into January', nextMonthStart(dec).getFullYear() === 2027 && nextMonthStart(dec).getMonth() === 0);
const bad = mem(); bad.setItem('letterscan.scans.v1', '{oops');
ok('corrupt counter reads as 0 used', scansUsed(oct, bad) === 0);
ok('sample not counted: canScan is not consulted and nothing is counted without countScan', scansUsed(oct, mem()) === 0);
ok('save: 0 saved -> may save 1', canSaveAnother(false, 0, true));
ok('save: 1 saved -> 2nd blocked in Core', !canSaveAnother(false, 1, true));
ok('save: Pro -> unlimited', canSaveAnother(true, 50, true));
ok('save: Pro off in build -> unlimited', canSaveAnother(false, 50, false));
ok('trial: free intro offer + eligible -> trial', offersFreeTrial({ introductoryPrice: { price: 0 }, introEligibility: 2 }));
ok('trial: eligibility unknown -> trial shown', offersFreeTrial({ introductoryPrice: { price: 0 } }));
ok('trial: ineligible (used before) -> no trial', !offersFreeTrial({ introductoryPrice: { price: 0 }, introEligibility: 1 }));
ok('trial: no intro offer -> no trial', !offersFreeTrial({ introductoryPrice: null }) && !offersFreeTrial(null));
ok('trial: paid intro price is not a free trial', !offersFreeTrial({ introductoryPrice: { price: 0.99 } }));
const keys = ['core_scans_left', 'core_limit_title', 'core_limit_body', 'core_save_title', 'core_save_body', 'core_replace', 'core_pro_only', 'core_steps_teaser', 'core_pdf_first', 'core_free_note', 'pro_lead_core', 'pro_f_unlimited', 'pro_f_plan', 'pro_f_voices', 'pro_f_history', 'pro_f_export', 'pro_f_qr', 'pro_trial_line', 'pro_start_trial', 'pro_trial_terms', 'pro_price_store'] as const;
const ph = (x: string) => (x.match(/\{\w+\}/g) ?? []).sort().join();
for (const k of keys) ok(`${k}: 18 languages, same placeholders`, S2[k].length === 18 && S2[k].every((x) => x.trim().length > 0 && ph(x) === ph(S2[k][0])));
ok('trial terms: 7 days, {price}, 24 hours, Apple ID in every language', S2.pro_trial_terms.every((x) => /7|۷/.test(x) && x.includes('{price}') && /24|۲۴/.test(x) && /Apple[ -]ID|Apple Kimliği/.test(x)));
ok('English trial terms: renews automatically, cancel 24 hours before the trial ends', /renews automatically every month/.test(S2.pro_trial_terms[0]) && /24 hours before the trial ends/.test(S2.pro_trial_terms[0]));
console.log(`${n - fail} limits checks passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
